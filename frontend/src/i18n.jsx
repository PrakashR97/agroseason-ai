const LangContext = createContext(null)

export function LangProvider({ children, initial }) {
  const [lang, setLangState] = useState(() => initial || localStorage.getItem('lang') || 'en')
  useEffect(() => {
    localStorage.setItem('lang', lang)
    document.documentElement.lang = lang
  }, [lang])
  const t = useCallback((key) => STRINGS[lang][key] ?? STRINGS.en[key] ?? key, [lang])
  const value = useMemo(() => ({
    lang, setLang: setLangState, t, months: MONTHS[lang],
    name: (o, base = 'name') => (lang === 'ta' ? o[`${base}_ta`] : o[`${base}_en`]),
    altName: (o, base = 'name') => (lang === 'ta' ? o[`${base}_en`] : o[`${base}_ta`]),
  }), [lang, t])
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export const useLang = () => useContext(LangContext)
